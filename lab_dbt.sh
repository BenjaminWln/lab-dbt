PY="$RUN python"
duck() {
  $PY "$ROOT/scripts/duck.py" "$@"
}
dbt_try() {
  if "$@"; then
    return 0
  else
    status=$?
  fi
  echo ">>> command failed with exit code $status: $*" >&2
  return 0
}

if [ "$USE_S3" = 1 ]; then
  aws s3 --profile default ls "s3://$LAB_BUCKET_NAME/bronze/"
